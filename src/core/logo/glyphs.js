export const GW = 5;
export const GH = 7;

// 字符的墨迹列范围（left/right 为字模列号，width = right - left + 1）
export function inkColsOf(ch) {
  const rows = GLYPHS[ch] || GLYPHS.o;
  let left = GW;
  let right = -1;
  for (let c = 0; c < GW; c++) {
    for (let r = 0; r < GH; r++) {
      if (rows[r][c] === '1') {
        if (c < left) left = c;
        if (c > right) right = c;
        break;
      }
    }
  }
  if (right < left) return { left: 0, width: GW }; // 全空（空格）按定宽
  return { left, width: right - left + 1 };
}

// 整词的实际墨迹行范围（用于按视觉中心对齐，而不是按 7 行 em 框）
export function inkBounds(chars) {
  let minRow = GH;
  let maxRow = 0;
  for (const ch of chars) {
    const rows = GLYPHS[ch] || GLYPHS.o;
    for (let r = 0; r < GH; r++) {
      if (rows[r].includes('1')) {
        if (r < minRow) minRow = r;
        if (r > maxRow) maxRow = r;
      }
    }
  }
  if (minRow > maxRow) return { minRow: 0, maxRow: GH - 1 };
  return { minRow, maxRow };
}
